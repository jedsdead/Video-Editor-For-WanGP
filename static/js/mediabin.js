// Media bin panel: import (upload or browse WanGP output folders), thumbnails, processing status, drag to timeline.
import * as M from "./model.js";
import { state, P, bus } from "./model.js";
import { api, el, toast, modal, shortTime, fmtBytes, showMenu } from "./util.js";

export class MediaBin {
  constructor(app) {
    this.app = app;
    this.filter = "";
    this.fileInput = el("input", { type: "file", multiple: true, accept: "video/*,audio/*,image/*", style: { display: "none" },
      onchange: (e) => { this.importFiles([...e.target.files]); e.target.value = ""; } });
    this.grid = el("div.media-grid");
    this.hint = el("div.drop-hint", {}, "Drop video, audio or image files here, or use Import / Browse.");
    this.node = el("div", {},
      el("div.panel-toolbar", {},
        el("button.small", { onclick: () => this.fileInput.click(), title: "Upload files from this computer (copied into the editor's media folder)" }, "Import files"),
        el("button.small", { onclick: () => this.browse(), title: "Pick files already on the WanGP machine (used in place, nothing copied)" }, "Browse outputs…"),
        el("input", { type: "search", placeholder: "Filter", style: { flex: "1", minWidth: "60px" }, oninput: (e) => { this.filter = e.target.value.toLowerCase(); this.render(); } }),
        this.fileInput),
      el("div.panel-scroll", {}, this.grid, this.hint));
    const scroll = this.node.querySelector(".panel-scroll");
    scroll.addEventListener("dragover", (e) => { if ([...e.dataTransfer.types].includes("Files")) { e.preventDefault(); this.hint.classList.add("dragover"); } });
    scroll.addEventListener("dragleave", () => this.hint.classList.remove("dragover"));
    scroll.addEventListener("drop", (e) => { e.preventDefault(); this.hint.classList.remove("dragover"); if (e.dataTransfer.files.length) this.importFiles([...e.dataTransfer.files]); });
    for (const name of ["project", "media-updated", "media"]) bus.on(name, () => this.render());
    this.poll();
  }

  items() { return Object.values(P().media || {}).filter(i => !i.generator); }

  render() {
    if (!P()) return;
    this.grid.innerHTML = "";
    const items = this.items().filter(i => !this.filter || i.name.toLowerCase().includes(this.filter));
    this.hint.hidden = items.length > 0 && !this.filter ? false : false;
    const title = P().media[M.TITLE_MEDIA.id];
    if (title && (!this.filter || "title".includes(this.filter))) this.grid.append(this.titleTile(title));
    for (const item of items) this.grid.append(this.tile(item));
  }

  // The title generator: drag onto a video track (or double-click) for a new text clip.
  titleTile(item) {
    const thumb = el("div.thumb.title-thumb", {}, el("span.kind", {}, "GENERATOR"), el("div.busy", { style: { background: "transparent", fontSize: "30px", fontWeight: "700", color: "#ffd9a8" } }, "T"));
    return el("div.media-item.title", {
      draggable: true, title: "Title: drag onto a video track, or double-click to add it at the playhead on the top video track",
      ondragstart: (e) => { e.dataTransfer.setData("text/x-ve-media", item.id); e.dataTransfer.effectAllowed = "copy"; window.__veDragMedia = item.id; },
      ondragend: () => { window.__veDragMedia = null; },
      ondblclick: () => this.addTitle(),
    }, thumb, el("div.name", {}, "Title"));
  }

  addTitle(at = null) {
    const tracks = M.videoTracks();
    const clips = M.edit("Add title", () => M.placeMedia(P().media[M.TITLE_MEDIA.id], tracks[tracks.length - 1].id, at ?? state.playhead));
    if (clips) { M.select(clips.map(c => c.id)); this.app.docks.show("inspector"); }
  }

  tile(item) {
    const busy = ["pending", "stale"].includes(item.proxy) || ["pending", "stale"].includes(item.thumbs);
    const thumb = el("div.thumb", {}, el("span.kind", {}, item.kind === "video" ? (item.has_audio ? "VIDEO+AUDIO" : "VIDEO") : item.kind.toUpperCase()),
      item.kind !== "image" ? el("span.dur", {}, shortTime(item.duration || 0)) : null,
      item.has_metadata ? el("span.gen", { title: "Generated by WanGP: prompt and settings available" }, "WanGP") : null,
      busy ? el("div.busy", {}, "Preparing preview…") : null,
      item.missing ? el("div.busy", { style: { color: "#ff7a7a" } }, "File missing") : null,
      item.kind === "audio" ? el("div.busy", { style: { background: "transparent", fontSize: "26px" } }, "♪") : null);
    if (item.kind === "video" && item.thumbs === "ready") {
      thumb.style.backgroundImage = `url(api/media/${item.id}/thumbs)`;
      thumb.style.backgroundSize = `${(item.thumb_count || 1) * 100}% 100%`;
      thumb.style.backgroundPosition = "0 0";
    } else if (item.kind === "image") thumb.style.backgroundImage = `url(api/media/${item.id}/original)`;
    const node = el(`div.media-item.${item.kind}${state.selectedMedia === item.id ? ".selected" : ""}`, {
      draggable: true, title: `${item.name}\n${item.width ? `${item.width}×${item.height}  ` : ""}${item.fps ? `${item.fps} fps  ` : ""}${item.path}`,
      ondragstart: (e) => { e.dataTransfer.setData("text/x-ve-media", item.id); e.dataTransfer.effectAllowed = "copy"; window.__veDragMedia = item.id; },
      ondragend: () => { window.__veDragMedia = null; },
      onclick: () => { state.selectedMedia = item.id; M.clearSelection(); this.render(); bus.emit("media-selected", item.id); },
      ondblclick: () => this.addToTimeline(item),
      oncontextmenu: (e) => { e.preventDefault(); this.menu(e, item); },
    }, thumb, el("div.name", {}, item.name));
    return node;
  }

  menu(e, item) {
    const used = P().clips.some(c => c.mediaId === item.id);
    showMenu(e.clientX, e.clientY, [
      { label: "Add to end of timeline", action: () => this.addToTimeline(item) },
      { label: "Insert at playhead", action: () => this.addToTimeline(item, state.playhead) },
      "-",
      { label: "Copy file path", action: () => navigator.clipboard?.writeText(item.path).then(() => toast("Path copied")) },
      { label: used ? "Remove from project (in use)" : "Remove from project", disabled: used,
        action: () => M.edit("Remove media", () => { delete P().media[item.id]; bus.emit("media"); }) },
    ]);
  }

  addToTimeline(item, at = null) {
    const pid = M.primaryId();
    const t = at ?? (P().magnetic ? M.clipsOn(pid).reduce((m, c) => Math.max(m, M.clipEnd(c)), 0) : M.timelineEnd());
    const clips = M.edit("Add clip", () => M.placeMedia(item, item.kind === "audio" ? M.audioTracks()[0].id : pid, t));
    if (clips) M.select(clips.map(c => c.id));
  }

  register(list, place) {
    let added = [];
    M.edit("Import media", () => { for (const item of list) M.registerMedia(item); });
    if (place && list.length) {
      let t = place.time;
      M.edit("Add clips", () => {
        for (const item of list) {
          const clips = M.placeMedia(item, place.trackId, t);
          added.push(...clips);
          t = Math.max(...clips.map(c => M.clipEnd(c)));
        }
      });
      if (added.length) M.select(added.map(c => c.id));
    }
    this.render();
    bus.emit("media");
    this.poll(true);
  }

  async importFiles(files, place = null) {
    if (!files.length) return;
    const total = files.reduce((s, f) => s + f.size, 0);
    toast(`Uploading ${files.length} file${files.length > 1 ? "s" : ""} (${fmtBytes(total)})…`);
    const form = new FormData();
    for (const f of files) form.append("files", f, f.name);
    try {
      const res = await api("api/upload", { method: "POST", body: form });
      for (const err of res.errors) toast(`${err.path}: ${err.error}`, "error", 6000);
      this.register(res.media, place);
      if (res.media.length) toast(`Imported ${res.media.length} file${res.media.length > 1 ? "s" : ""}`);
    } catch (e) { toast(`Upload failed: ${e.message}`, "error", 6000); }
  }

  async importPaths(paths, place = null) {
    try {
      const res = await api("api/import", { method: "POST", body: { paths } });
      for (const err of res.errors) toast(`${err.path}: ${err.error}`, "error", 6000);
      this.register(res.media, place);
      if (res.media.length) toast(`Imported ${res.media.length} file${res.media.length > 1 ? "s" : ""}`);
    } catch (e) { toast(`Import failed: ${e.message}`, "error", 6000); }
  }

  async poll(immediate = false) {
    clearTimeout(this.pollTimer);
    const run = async () => {
      if (!P()) return this.poll();
      const pending = this.items().filter(i => ["pending", "stale"].includes(i.proxy) || ["pending", "stale"].includes(i.thumbs) || ["pending", "stale"].includes(i.wave) || i.proxy_rev === "pending");
      if (pending.length) {
        try {
          const res = await api("api/media/batch", { method: "POST", body: { ids: pending.map(i => i.id) } });
          for (const [id, info] of Object.entries(res)) {
            if (!info || !P().media[id] || P().media[id].generator) continue;
            const before = P().media[id];
            const changed = ["proxy", "proxy_rev", "thumbs", "wave"].some(k => before[k] !== info[k]);
            P().media[id] = { ...before, ...info };
            if (changed) bus.emit("media-updated", id);
          }
        } catch (_) { /* server busy; retry */ }
      }
      this.poll();
    };
    this.pollTimer = setTimeout(run, immediate ? 300 : 1500);
  }

  async refreshAll() {
    const ids = this.items().map(i => i.id);
    if (!ids.length) return;
    try {
      const res = await api("api/media/batch", { method: "POST", body: { ids } });
      for (const [id, info] of Object.entries(res)) {
        if (!P().media[id] || P().media[id].generator) continue;
        if (!info) P().media[id].missing = true;
        else P().media[id] = { ...P().media[id], ...info };
      }
      bus.emit("media");
      bus.emit("change");
    } catch (_) { /* offline */ }
  }

  // ---------------------------------------------------------------- server file browser
  async browse(startPath = null) {
    const status = this.app.status || {};
    const selected = new Set();
    const pathInput = el("input", { type: "text" });
    const list = el("div.browser-list");
    const count = el("span.dim");
    let current = null;
    const load = async (path) => {
      list.innerHTML = "";
      list.append(el("div.empty-note", {}, "Loading…"));
      try {
        const data = await api(`api/browse?path=${encodeURIComponent(path || "")}`);
        current = data;
        localStorage.setItem("ve_browse_path", data.path);
        pathInput.value = data.path;
        list.innerHTML = "";
        if (data.parent) list.append(el("div.brow.dir", { onclick: () => load(data.parent) }, el("span", {}, "↰"), el("span", {}, ".."), el("span"), el("span")));
        for (const d of data.dirs) list.append(el("div.brow.dir", { onclick: () => load(d.path) }, el("span", {}, "📁"), el("span", {}, d.name), el("span"), el("span")));
        for (const f of data.files) {
          const row = el(`div.brow${selected.has(f.path) ? ".sel" : ""}`, {
            onclick: (e) => {
              if (selected.has(f.path)) selected.delete(f.path); else selected.add(f.path);
              row.classList.toggle("sel", selected.has(f.path));
              count.textContent = selected.size ? `${selected.size} selected` : "";
            },
            ondblclick: () => { selected.add(f.path); doImport(); },
          }, el("span", {}, f.kind === "video" ? "🎞" : f.kind === "audio" ? "♪" : "🖼"), el("span", {}, f.name),
             el("span.meta", {}, fmtBytes(f.size)), el("span.meta", {}, new Date(f.mtime * 1000).toLocaleString([], { dateStyle: "short", timeStyle: "short" })));
          list.append(row);
        }
        if (!data.dirs.length && !data.files.length) list.append(el("div.empty-note", {}, "No media files here."));
      } catch (e) { list.innerHTML = ""; list.append(el("div.empty-note", {}, e.message)); }
    };
    const doImport = () => { if (selected.size) { this.importPaths([...selected]); m.close(); } };
    const roots = el("div.browser-roots", {}, (status.roots || []).map(r => el("button.small", { onclick: () => load(r.path), title: r.path }, r.label)));
    const body = el("div", {}, roots,
      el("div.browser-path", {}, pathInput, el("button.small", { onclick: () => load(pathInput.value) }, "Go")),
      list,
      el("div.dim", { style: { marginTop: "6px", fontSize: "12px" } }, "Newest files first. Files are used where they are; nothing is copied."));
    pathInput.addEventListener("keydown", (e) => { if (e.key === "Enter") load(pathInput.value); });
    const m = modal({ title: "Browse media on the WanGP machine", body, buttons: [
      { custom: true, label: "Select all files", close: false, action: () => { for (const f of current?.files || []) selected.add(f.path); load(current.path); count.textContent = `${selected.size} selected`; return false; } },
      "spacer", { label: "Cancel" }, { label: "Import selected", primary: true, action: () => { doImport(); return false; } }] });
    m.footer.insertBefore(count, m.footer.children[1]);
    load(startPath || localStorage.getItem("ve_browse_path") || (status.roots && status.roots[0]?.path) || "");
  }
}
